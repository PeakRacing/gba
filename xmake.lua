set_project("gba")
set_version("0.1.0")
set_xmakever("3.0.0")
set_languages("c11")
add_rules("mode.debug", "mode.release")
set_warnings("allextra")
add_cflags("/utf-8", "/wd4996", {tools = "cl"})

local function sources()
    add_includedirs("inc", "src", "port")
    add_files("src/*.c")
end
target("gba-core", function()
    set_kind("static")
    sources()
end)
local function tests(name, definitions)
    target(name, function()
        set_kind("binary")
        set_rundir(os.projectdir())
        sources()
        add_files("test/main.c", "test/port.c", "test/files.c")
        add_defines("GBA_TEST_MODE=1", "GBA_CUSTOM_TICKS=1", "GBA_CUSTOM_OUTPUT=1", "GBA_CUSTOM_FRAME=1", "GBA_CUSTOM_TEST_HOOK=1")
        add_defines(table.unpack(definitions))
    end)
end
tests("gba-tests", {})
tests("gba-tests-full", {"GBA_USE_FS=1", "GBA_ENABLE_SOUND=1", "GBA_ENABLE_SAVE_STATE=1", "GBA_COLOR_DEPTH=32"})
tests("gba-tests-stream", {"GBA_USE_FS=1", "GBA_ENABLE_SOUND=1", "GBA_ENABLE_SAVE_STATE=1", "GBA_ROM_STREAM=1", "GBA_RAM_LACK=1"})
tests("gba-tests-minimal", {"GBA_ENABLE_SAVE=0", "GBA_ENABLE_RTC=0", "GBA_BIOS_HLE=0", "GBA_RAM_LACK=1"})
tests("gba-tests-skip", {"GBA_USE_FS=1", "GBA_ENABLE_SOUND=1", "GBA_FRAME_SKIP=2", "GBA_COLOR_SWAP=1"})
target("gba-tests-small-save", function()
    set_kind("binary")
    sources()
    add_defines("GBA_SAVE_CAPACITY=512")
    add_files("port/gba_default.c", "port/gba_port.c", "test/small_save.c")
end)
