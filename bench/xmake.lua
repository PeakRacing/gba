target("gba-bench", function()
    set_kind("binary")
    set_rundir(os.projectdir())
    add_includedirs("../inc", "../src", "../port")
    add_files("../src/*.c", "../port/gba_port.c", "../port/gba_default.c", "main.c")
    add_defines("GBA_USE_FS=1", "GBA_ENABLE_SOUND=1", "GBA_ROM_STREAM=1", "GBA_TEST_PROFILE=1")
end)

local function speed(name, definitions)
    target(name, function()
        set_kind("binary")
        set_rundir(os.projectdir())
        add_includedirs("../inc", "../src", "../port")
        add_files("../src/*.c", "../port/gba_port.c", "../port/gba_default.c", "fast.c")
        add_defines("GBA_USE_FS=1", "GBA_CUSTOM_TICKS=1")
        add_defines(table.unpack(definitions))
    end)
end
speed("gba-speed565", {"GBA_ENABLE_SOUND=1"})
speed("gba-speed32", {"GBA_ENABLE_SOUND=1", "GBA_COLOR_DEPTH=32"})
speed("gba-speed-stream", {"GBA_ENABLE_SOUND=1", "GBA_ROM_STREAM=1", "GBA_RAM_LACK=1"})
speed("gba-speed-silent", {})
